export const mergeDailyRecords = (records, valuesField = "outlets") => {
  const byDate = new Map();

  (Array.isArray(records) ? records : []).forEach((record) => {
    const date = String(record?.date || "").slice(0, 10);
    if (!date) return;

    const existing = byDate.get(date) || { ...record, date, [valuesField]: {} };
    const mergedValues = { ...(existing[valuesField] || {}) };

    Object.entries(record?.[valuesField] || {}).forEach(([key, value]) => {
      const current = Number(mergedValues[key]) || 0;
      const next = Number(value) || 0;
      if (mergedValues[key] === undefined || next !== 0 || current === 0) {
        mergedValues[key] = value;
      }
    });

    // Date-level records can be created both by the automatic final sync and
    // by a later manual Data Entry save. Preserve outlet-level metadata from
    // both documents; spreading the last record used to discard the manual
    // marker and made a real zero look like an unfinished placeholder.
    const mergeOutletMetadata = (field) => ({
      ...(existing[field] || {}),
      ...(record?.[field] || {}),
    });

    byDate.set(date, {
      ...existing,
      ...record,
      date,
      [valuesField]: mergedValues,
      addedByPerOutlet: mergeOutletMetadata("addedByPerOutlet"),
      manuallyEnteredOutlets: mergeOutletMetadata("manuallyEnteredOutlets"),
      auditStatuses: mergeOutletMetadata("auditStatuses"),
      auditedByPerOutlet: mergeOutletMetadata("auditedByPerOutlet"),
      autoGenerated: Boolean(existing.autoGenerated) && Boolean(record.autoGenerated),
      finalSourceSync: Boolean(existing.finalSourceSync) || Boolean(record.finalSourceSync),
    });
  });

  return Array.from(byDate.values());
};
